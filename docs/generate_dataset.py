def add_sheet(title, headers, rows, widths=None, wrap_cols=None):
    ws = workbook.create_sheet(title)
    ws.append(headers)
    for cell in ws[1]:
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(vertical="center", horizontal="left")
        cell.border = BORDER
    for r in rows:
        ws.append(r)
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = "A1:%s%d" % (get_column_letter(len(headers)), max(1, len(rows) + 1))
    for idx, name in enumerate(headers, start=1):
        letter = get_column_letter(idx)
        w = (widths or {}).get(name, min(30, max(12, len(name) + 3)))
        ws.column_dimensions[letter].width = w
    if wrap_cols:
        for idx, name in enumerate(headers, start=1):
            if name in wrap_cols:
                for row in range(2, len(rows) + 2):
                    ws.cell(row=row, column=idx).alignment = Alignment(wrap_text=True, vertical="top")
    ws.row_dimensions[1].height = 22
    return ws


